import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const archive = JSON.parse(await readFile(new URL("design/figma-icons.json", root), "utf8"));
const inventory = JSON.parse(await readFile(new URL("design/figma-components.json", root), "utf8"));
const page = inventory.pages.find((entry) => entry.page.id === archive.pageId);
assert.equal(archive.fileKey, inventory.fileKey);
assert.equal(archive.icons.length, 1173);
assert.deepEqual(
  new Set(archive.icons.map((icon) => icon.id)),
  new Set(page.families.map((family) => family.id))
);
const names = new Map();
for (const icon of archive.icons) names.set(icon.name, (names.get(icon.name) ?? 0) + 1);
const directory = new URL("assets/icons/", root);
const checking = process.argv.includes("--check");
if (!checking) await mkdir(directory, { recursive: true });
const records = archive.icons.map((icon, index) => {
  const family = page.families.find((entry) => entry.id === icon.id);
  assert.equal(icon.name, family.name);
  assert.equal(family.variantCount, 0);
  assert.match(icon.svg, /^<svg\s/);
  assert.doesNotMatch(
    icon.svg,
    /<(?:script|foreignObject)\b|\bon\w+\s*=|(?:href|src)="https?:\/\//i
  );
  const rootTag = icon.svg.slice(0, icon.svg.indexOf(">") + 1);
  const width = Number(rootTag.match(/\bwidth="([\d.]+)"/)?.[1]);
  const height = Number(rootTag.match(/\bheight="([\d.]+)"/)?.[1]);
  assert.ok(width > 0 && height > 0);
  return {
    name: names.get(icon.name) > 1 ? `${icon.name}-${icon.id.replace(":", "-")}` : icon.name,
    sourceName: icon.name,
    nodeId: icon.id,
    file: `${icon.id.replace(":", "-")}.svg`,
    width,
    height,
    sha256: createHash("sha256").update(icon.svg).digest("hex"),
    importName: `icon${index}`,
  };
});
assert.equal(new Set(records.map((record) => record.name)).size, records.length);
for (let index = 0; index < records.length; index++) {
  const target = new URL(records[index].file, directory);
  const source = archive.icons[index].svg;
  if (checking)
    assert.equal(
      await readFile(target, "utf8"),
      source,
      `Original SVG changed: ${records[index].nodeId}`
    );
  else await writeFile(target, source);
}
assert.deepEqual(new Set(await readdir(directory)), new Set(records.map((record) => record.file)));
const registry = [
  "// Generated by scripts/generate-icons.mjs. Preserve the original SVG assets.",
  ...records.map(
    (record) => `import ${record.importName} from "../../assets/icons/${record.file}";`
  ),
  "",
  "export const figmaIcons = {",
  ...records.map(
    (record) =>
      `  ${JSON.stringify(record.name)}: { asset: ${record.importName}, sourceName: ${JSON.stringify(record.sourceName)}, nodeId: ${JSON.stringify(record.nodeId)}, width: ${record.width}, height: ${record.height} },`
  ),
  "} as const;",
  "",
  "export type FigmaIconName = keyof typeof figmaIcons;",
  "export const figmaIconNames = Object.keys(figmaIcons) as FigmaIconName[];",
  "export function figmaIconUrl(name: FigmaIconName): string {",
  "  const asset = figmaIcons[name].asset;",
  '  return typeof asset === "string" ? asset : asset.src;',
  "}",
  "",
].join("\n");
const manifest = {
  fileKey: archive.fileKey,
  pageId: archive.pageId,
  count: records.length,
  duplicateNames: [...names]
    .filter(([, count]) => count > 1)
    .map(([name, count]) => ({ name, count })),
  icons: records.map(({ importName: _importName, ...record }) => record),
};
for (const [path, output] of [
  ["src/components/figma-icons.ts", registry],
  ["design/figma-icons.manifest.json", JSON.stringify(manifest, null, 2) + "\n"],
]) {
  const target = new URL(path, root);
  if (checking)
    assert.equal(await readFile(target, "utf8"), output, `Generated icon file is stale: ${path}`);
  else await writeFile(target, output);
}
console.log(
  `Original icons: ${records.length}; all source IDs, SVG bytes and duplicate names verified.`
);
