BEGIN;
CREATE OR REPLACE FUNCTION public.match_documents_hybrid( -- [DIM 1536]
    query_text text, -- [DIM 1536]
    query_embedding vector(1536), -- [DIM 1536]
    match_threshold double precision DEFAULT 0.25, -- [DIM 1536]
    match_count integer DEFAULT 10, -- [DIM 1536]
    filter_university_id uuid DEFAULT NULL, -- [DIM 1536]
    filter_levels public.university_level[] DEFAULT NULL, -- [DIM 1536]
    filter_doc_ids uuid[] DEFAULT NULL -- [DIM 1536]
) -- [DIM 1536]
RETURNS TABLE ( -- [DIM 1536]
    chunk_id uuid, -- [DIM 1536]
    document_id uuid, -- [DIM 1536]
    chunk_index integer, -- [DIM 1536]
    content text, -- [DIM 1536]
    content_type text, -- [DIM 1536]
    page_start integer, -- [DIM 1536]
    page_end integer, -- [DIM 1536]
    bounding_box jsonb, -- [DIM 1536]
    section_id uuid, -- [DIM 1536]
    segment_id uuid, -- [DIM 1536]
    dense_score double precision, -- [DIM 1536]
    fts_score double precision, -- [DIM 1536]
    trgm_score double precision, -- [DIM 1536]
    rrf_score double precision -- [DIM 1536]
) -- [DIM 1536]
LANGUAGE plpgsql SET pg_trgm.word_similarity_threshold TO '0.20' STABLE -- [DIM 1536]
AS $$ -- [DIM 1536]
DECLARE -- [DIM 1536]
    k CONSTANT double precision := 60.0; -- [DIM 1536]
BEGIN -- [DIM 1536]
    RETURN QUERY -- [DIM 1536]
    WITH -- [DIM 1536]
    candidate_docs AS ( -- [DIM 1536]
        SELECT d.id -- [DIM 1536]
        FROM public.documents d -- [DIM 1536]
        WHERE d.deleted_at IS NULL -- [DIM 1536]
          AND d.status = 'active' -- [DIM 1536]
          AND filter_university_id IS NOT NULL AND d.university_id = filter_university_id -- [DIM 1536]
          AND (filter_doc_ids IS NULL OR d.id = ANY(filter_doc_ids))
          AND (filter_levels IS NULL OR cardinality(d.target_levels)=0 OR d.target_levels && filter_levels) -- [DIM 1536]
    ), -- [DIM 1536]
    vector_pool AS ( -- [DIM 1536]
        SELECT -- [DIM 1536]
            c.id, -- [DIM 1536]
            1.0 - ((c.embedding::halfvec(1536)) <=> (query_embedding::halfvec(1536))) AS score, -- [DIM 1536]
            ROW_NUMBER() OVER (ORDER BY ((c.embedding::halfvec(1536)) <=> (query_embedding::halfvec(1536))) ASC) AS rank -- [DIM 1536]
        FROM public.document_chunks c -- [DIM 1536]
        JOIN candidate_docs cd ON cd.id = c.document_id -- [DIM 1536]
        WHERE c.embedding IS NOT NULL -- [DIM 1536]
          AND (1.0 - ((c.embedding::halfvec(1536)) <=> (query_embedding::halfvec(1536)))) >= match_threshold -- [DIM 1536]
        ORDER BY (c.embedding::halfvec(1536)) <=> (query_embedding::halfvec(1536)) ASC -- [DIM 1536]
        LIMIT 40 -- [DIM 1536]
    ), -- [DIM 1536]
    fts_pool AS ( -- [DIM 1536]
        SELECT -- [DIM 1536]
            c.id, -- [DIM 1536]
            ts_rank_cd(c.content_fts, websearch_to_tsquery('english', query_text))::double precision AS score, -- [DIM 1536]
            ROW_NUMBER() OVER (ORDER BY ts_rank_cd(c.content_fts, websearch_to_tsquery('english', query_text)) DESC) AS rank -- [DIM 1536]
        FROM public.document_chunks c -- [DIM 1536]
        JOIN candidate_docs cd ON cd.id = c.document_id -- [DIM 1536]
        WHERE c.content_fts @@ websearch_to_tsquery('english', query_text) -- [DIM 1536]
        ORDER BY score DESC -- [DIM 1536]
        LIMIT 40 -- [DIM 1536]
    ), -- [DIM 1536]
    trgm_pool AS ( -- [DIM 1536]
        SELECT -- [DIM 1536]
            c.id, -- [DIM 1536]
            word_similarity(query_text, c.content)::double precision AS score, -- [DIM 1536]
            ROW_NUMBER() OVER (ORDER BY word_similarity(query_text, c.content) DESC) AS rank -- [DIM 1536]
        FROM public.document_chunks c -- [DIM 1536]
        JOIN candidate_docs cd ON cd.id = c.document_id -- [DIM 1536]
        WHERE c.content %> query_text -- [DIM 1536]
        ORDER BY score DESC -- [DIM 1536]
        LIMIT 40 -- [DIM 1536]
    ), -- [DIM 1536]
    combined_ids AS ( -- [DIM 1536]
        SELECT id FROM vector_pool -- [DIM 1536]
        UNION -- [DIM 1536]
        SELECT id FROM fts_pool -- [DIM 1536]
        UNION -- [DIM 1536]
        SELECT id FROM trgm_pool -- [DIM 1536]
    ), -- [DIM 1536]
    ranked_chunks AS ( -- [DIM 1536]
        SELECT -- [DIM 1536]
            cid.id, -- [DIM 1536]
            COALESCE(vp.score, 0.0) AS dense_score, -- [DIM 1536]
            COALESCE(fp.score, 0.0) AS fts_score, -- [DIM 1536]
            COALESCE(tp.score, 0.0) AS trgm_score, -- [DIM 1536]
            ( -- [DIM 1536]
                COALESCE(1.0 / (k + vp.rank), 0.0) + -- [DIM 1536]
                COALESCE(1.0 / (k + fp.rank), 0.0) + -- [DIM 1536]
                COALESCE(1.0 / (k + tp.rank), 0.0) -- [DIM 1536]
            ) AS rrf_score -- [DIM 1536]
        FROM combined_ids cid -- [DIM 1536]
        LEFT JOIN vector_pool vp ON vp.id = cid.id -- [DIM 1536]
        LEFT JOIN fts_pool fp ON fp.id = cid.id -- [DIM 1536]
        LEFT JOIN trgm_pool tp ON tp.id = cid.id -- [DIM 1536]
    ) -- [DIM 1536]
    SELECT -- [DIM 1536]
        c.id AS chunk_id, -- [DIM 1536]
        c.document_id, -- [DIM 1536]
        c.chunk_index, -- [DIM 1536]
        c.content, -- [DIM 1536]
        'text'::text AS content_type, -- [DIM 1536]
        c.page_start, -- [DIM 1536]
        c.page_end, -- [DIM 1536]
        c.bounding_box, -- [DIM 1536]
        NULL::uuid AS section_id, -- [DIM 1536]
        c.segment_id, -- [DIM 1536]
        rc.dense_score, -- [DIM 1536]
        rc.fts_score, -- [DIM 1536]
        rc.trgm_score, -- [DIM 1536]
        rc.rrf_score -- [DIM 1536]
    FROM ranked_chunks rc -- [DIM 1536]
    JOIN public.document_chunks c ON c.id = rc.id -- [DIM 1536]
    ORDER BY rc.rrf_score DESC -- [DIM 1536]
    LIMIT match_count; -- [DIM 1536]
END; -- [DIM 1536]
$$;
COMMIT;
