@pytest.mark.parametrize(  # [CHAT FIX]
    "key,role,expected",  # [CHAT FIX]
    [  # [CHAT FIX]
        (f"universities/{UNI}/courses/test/original/document.pdf", "student", 404),  # [CHAT FIX]
        (  # [CHAT FIX]
            f"universities/{UNI}/courses/test/converted/document.pdf",  # [CHAT FIX]
            "super_admin",  # [CHAT FIX]
            404,  # [CHAT FIX]
        ),  # [CHAT FIX]
        (f"artifacts/{UNI}/{OWNER}/pdf/../document.pdf", "student", 404),  # [CHAT FIX]
        (f"artifacts/{UNI}/{OTHER}/pdf/file.pdf", "student", 404),  # [CHAT FIX]
        (f"artifacts/{UNI}/{OWNER}/pdf/file.pdf", "student", 200),  # [CHAT FIX]
        (f"artifacts/{UNI}/{OTHER}/pdf/file.pdf", "super_admin", 200),  # [CHAT FIX]
    ],  # [CHAT FIX]
)  # [CHAT FIX]
def test_artifact_download_scope(  # [CHAT FIX]
    authenticated_student: UserContext,  # [CHAT FIX]
    monkeypatch: pytest.MonkeyPatch,  # [CHAT FIX]
    key: str,  # [CHAT FIX]
    role: str,  # [CHAT FIX]
    expected: int,  # [CHAT FIX]
) -> None:  # [CHAT FIX]
    authenticated_student["role"] = role  # [CHAT FIX]
    authenticated_student["roles"] = [role]  # [CHAT FIX]
    download = AsyncMock(return_value=b"offline artifact")  # [CHAT FIX]
    monkeypatch.setattr(library.storage_engine, "download_bytes", download)  # [CHAT FIX]
    response = TestClient(app).get(  # [CHAT FIX]
        "/api/v1/library/artifacts/download",  # [CHAT FIX]
        params={"key": key},  # [CHAT FIX]
    )  # [CHAT FIX]
    assert response.status_code == expected  # [CHAT FIX]
    if expected == 200:  # [CHAT FIX]
        assert response.content == b"offline artifact"  # [CHAT FIX]
        download.assert_awaited_once_with(key)  # [CHAT FIX]
    else:  # [CHAT FIX]
        assert response.json()["detail"] == "File not found."  # [CHAT FIX]
        download.assert_not_awaited()  # [CHAT FIX]


def test_artifact_key_has_its_own_prefix_and_owner() -> None:  # [CHAT FIX]
    artifact_id = str(uuid.uuid4())  # [CHAT FIX]
    key = build_artifact_storage_key(  # [CHAT FIX]
        "pdf",  # [CHAT FIX]
        "pdf",  # [CHAT FIX]
        artifact_id=artifact_id,  # [CHAT FIX]
        university_id=UNI,  # [CHAT FIX]
        user_id=OWNER,  # [CHAT FIX]
    )  # [CHAT FIX]
    assert key == f"artifacts/{UNI}/{OWNER}/pdf/{artifact_id}.pdf"  # [CHAT FIX]


