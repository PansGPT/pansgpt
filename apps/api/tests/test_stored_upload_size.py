@pytest.mark.parametrize("result", [0, 1234, "missing", "forbidden"])  # [LEFTOVER FIX]
async def test_head_returns_stored_size_or_missing(  # [LEFTOVER FIX]
    monkeypatch: pytest.MonkeyPatch,  # [LEFTOVER FIX]
    result: int | str,  # [LEFTOVER FIX]
) -> None:  # [LEFTOVER FIX]
    head = AsyncMock(return_value={"ContentLength": result})  # [LEFTOVER FIX]
    if isinstance(result, str):  # [LEFTOVER FIX]
        head.side_effect = ClientError(  # [LEFTOVER FIX]
            {"Error": {"Code": "404" if result == "missing" else "403"}},  # [LEFTOVER FIX]
            "HeadObject",  # [LEFTOVER FIX]
        )  # [LEFTOVER FIX]

    @asynccontextmanager  # [LEFTOVER FIX]
    async def client() -> AsyncIterator[SimpleNamespace]:  # [LEFTOVER FIX]
        yield SimpleNamespace(head_object=head)  # [LEFTOVER FIX]

    storage = R2StorageEngine()  # [LEFTOVER FIX]
    monkeypatch.setattr(storage, "get_client", client)  # [LEFTOVER FIX]
    if result == "forbidden":  # [LEFTOVER FIX]
        with pytest.raises(ClientError):  # [LEFTOVER FIX]
            await storage.get_object_size("original.pdf")  # [LEFTOVER FIX]
    else:  # [LEFTOVER FIX]
        assert await storage.get_object_size("original.pdf") == (  # [LEFTOVER FIX]
            None if result == "missing" else result  # [LEFTOVER FIX]
        )  # [LEFTOVER FIX]
    head.assert_awaited_once_with(  # [LEFTOVER FIX]
        Bucket=settings.r2_bucket_name,  # [LEFTOVER FIX]
        Key="original.pdf",  # [LEFTOVER FIX]
    )  # [LEFTOVER FIX]


@pytest.mark.parametrize("scenario", ["oversize", "normal", "missing"])  # [LEFTOVER FIX]
async def test_ingestion_checks_stored_size_before_processing(  # [LEFTOVER FIX]
    monkeypatch: pytest.MonkeyPatch,  # [LEFTOVER FIX]
    scenario: str,  # [LEFTOVER FIX]
) -> None:  # [LEFTOVER FIX]
    monkeypatch.setattr(settings, "MAX_UPLOAD_MB", 1)  # [LEFTOVER FIX]
    size = {"oversize": 1024 * 1024 + 1, "normal": 1024 * 1024, "missing": None}[  # [LEFTOVER FIX]
        scenario  # [LEFTOVER FIX]
    ]  # [LEFTOVER FIX]
    events: list[str] = []  # [LEFTOVER FIX]

    async def head(key: str) -> int | None:  # [LEFTOVER FIX]
        events.append("head")  # [LEFTOVER FIX]
        return size  # [LEFTOVER FIX]

    async def ingest(**kwargs: object) -> bool:  # [LEFTOVER FIX]
        events.append("ingest")  # [LEFTOVER FIX]
        return True  # [LEFTOVER FIX]

    storage = SimpleNamespace(  # [LEFTOVER FIX]
        get_object_size=AsyncMock(side_effect=head),  # [LEFTOVER FIX]
        download_bytes=AsyncMock(),  # [LEFTOVER FIX]
    )  # [LEFTOVER FIX]
    status = AsyncMock()  # [LEFTOVER FIX]
    pipeline = AsyncMock(side_effect=ingest)  # [LEFTOVER FIX]
    monkeypatch.setattr(tasks, "storage_engine", storage)  # [LEFTOVER FIX]
    monkeypatch.setattr(tasks, "_claim_document", AsyncMock(return_value=True))  # [LEFTOVER FIX]
    monkeypatch.setattr(tasks, "_get_document_meta", AsyncMock(return_value=None))  # [LEFTOVER FIX]
    monkeypatch.setattr(tasks, "_update_document_status", status)  # [LEFTOVER FIX]
    monkeypatch.setattr(tasks, "get_image_status", AsyncMock(return_value={}))  # [LEFTOVER FIX]
    monkeypatch.setattr(  # [LEFTOVER FIX]
        tasks.document_ingestion_engine,  # [LEFTOVER FIX]
        "ingest_document_from_r2",  # [LEFTOVER FIX]
        pipeline,  # [LEFTOVER FIX]
    )  # [LEFTOVER FIX]
    document_id = "018f3a10-0001-7000-8000-000000000001"  # [LEFTOVER FIX]
    if scenario == "normal":  # [LEFTOVER FIX]
        assert (  # [LEFTOVER FIX]
            await tasks.ingest_document_job({}, document_id, "original.pdf")  # [LEFTOVER FIX]
            is True  # [LEFTOVER FIX]
        )  # [LEFTOVER FIX]
        assert events == ["head", "ingest"]  # [LEFTOVER FIX]
        pipeline.assert_awaited_once_with(  # [LEFTOVER FIX]
            document_id=document_id,  # [LEFTOVER FIX]
            storage_key="original.pdf",  # [LEFTOVER FIX]
            worker_id=ANY,
        )  # [LEFTOVER FIX]
    else:  # [LEFTOVER FIX]
        message = (  # [LEFTOVER FIX]
            "Stored file exceeds the 1 MB upload limit."  # [LEFTOVER FIX]
            if scenario == "oversize"  # [LEFTOVER FIX]
            else "Original upload was not found in storage."  # [LEFTOVER FIX]
        )  # [LEFTOVER FIX]
        with pytest.raises(ValueError, match=message):  # [LEFTOVER FIX]
            await tasks.ingest_document_job({}, document_id, "original.docx")  # [LEFTOVER FIX]
        status.assert_any_await(document_id, status="failed", progress=0, worker_id=ANY)
        pipeline.assert_not_awaited()  # [LEFTOVER FIX]
        storage.download_bytes.assert_not_awaited()  # [LEFTOVER FIX]
        assert events == ["head"]  # [LEFTOVER FIX]
