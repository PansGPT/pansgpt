import re  # [CHAT FIX 2]
import uuid  # [CHAT FIX 2]
from unittest.mock import AsyncMock  # [CHAT FIX 2]

import pytest  # [CHAT FIX 2]
from fastapi.testclient import TestClient  # [CHAT FIX 2]

from app.main import app  # [CHAT FIX 2]
from app.routers import library  # [CHAT FIX 2]
from tests.conftest import TenantTestState  # [CHAT FIX 2]


@pytest.mark.parametrize(  # [CHAT FIX 2]
    "role,foreign,no_university,expected",  # [CHAT FIX 2]
    [  # [CHAT FIX 2]
        ("university_admin", False, False, 200),  # [CHAT FIX 2]
        ("university_admin", True, False, 404),  # [CHAT FIX 2]
        ("super_admin", True, False, 200),  # [CHAT FIX 2]
        ("super_admin", True, True, 200),  # [CHAT FIX 2]
        ("student", False, False, 403),  # [CHAT FIX 2]
    ],  # [CHAT FIX 2]
)  # [CHAT FIX 2]
def test_approval_uses_verified_reviewer_and_university_scope(  # [CHAT FIX 2]
    tenant_state: TenantTestState,  # [CHAT FIX 2]
    monkeypatch: pytest.MonkeyPatch,  # [CHAT FIX 2]
    role: str,  # [CHAT FIX 2]
    foreign: bool,  # [CHAT FIX 2]
    no_university: bool,  # [CHAT FIX 2]
    expected: int,  # [CHAT FIX 2]
) -> None:  # [CHAT FIX 2]
    tenant_state.user["role"] = role  # [CHAT FIX 2]
    tenant_state.user["roles"] = [role]  # [CHAT FIX 2]
    if no_university:  # [CHAT FIX 2]
        tenant_state.user["university_id"] = None  # [CHAT FIX 2]
    document_id = uuid.UUID(  # [CHAT FIX 2]
        "018f3a40-0001-7000-8000-000000000002"  # [CHAT FIX 2]
        if foreign  # [CHAT FIX 2]
        else "018f3a30-0001-7000-8000-000000000001"  # [CHAT FIX 2]
    )  # [CHAT FIX 2]
    row = tenant_state.documents[document_id]  # [CHAT FIX 2]
    row.update(  # [CHAT FIX 2]
        status="pending_review",  # [CHAT FIX 2]
        reviewed_by=None,  # [CHAT FIX 2]
        reviewed_at=None,  # [CHAT FIX 2]
        storage_key="universities/test/original/slides.pptx",  # [CHAT FIX 2]
    )  # [CHAT FIX 2]
    original_fetchrow = tenant_state.connection.fetchrow.side_effect  # [CHAT FIX 2]
    updates: list[tuple[str, tuple[object, ...]]] = []  # [CHAT FIX 2]

    async def fetchrow(sql: str, *args: object) -> dict | None:  # [CHAT FIX 2]
        if "UPDATE public.documents" not in sql:  # [CHAT FIX 2]
            return await original_fetchrow(sql, *args)  # [CHAT FIX 2]
        updates.append((sql, args))  # [CHAT FIX 2]
        if (  # [CHAT FIX 2]
            "university_id = $2" in sql  # [CHAT FIX 2]
            and args[1] is not None  # [CHAT FIX 2]
            and row["university_id"] != args[1]  # [CHAT FIX 2]
        ):  # [CHAT FIX 2]
            return None  # [CHAT FIX 2]
        for field, index in re.findall(r"(status|reviewed_by) = \$(\d+)", sql):  # [CHAT FIX 2]
            row[field] = args[int(index) - 1]  # [CHAT FIX 2]
        if "reviewed_at = now()" in sql:  # [CHAT FIX 2]
            row["reviewed_at"] = "database-now"  # [CHAT FIX 2]
        return {"id": document_id}  # [CHAT FIX 2]

    async def detail(*args: object, **kwargs: object) -> dict:  # [CHAT FIX 2]
        return dict(  # [CHAT FIX 2]
            id=str(document_id),  # [CHAT FIX 2]
            university_id=str(row["university_id"]),  # [CHAT FIX 2]
            title="Pending lecture",  # [CHAT FIX 2]
            course_code="PMB 411",  # [CHAT FIX 2]
            course_title="Microbiology",  # [CHAT FIX 2]
            storage_key=row["storage_key"],  # [CHAT FIX 2]
            page_count=7,  # [CHAT FIX 2]
            file_size_bytes=100,  # [CHAT FIX 2]
            mime_type="application/pdf",  # [CHAT FIX 2]
            status=row["status"],  # [CHAT FIX 2]
            embedding_status="pending",  # [CHAT FIX 2]
            embedding_progress=0,  # [CHAT FIX 2]
            total_chunks=0,  # [CHAT FIX 2]
            target_levels=[],  # [CHAT FIX 2]
            created_at="unit-created",  # [CHAT FIX 2]
        )  # [CHAT FIX 2]

    monkeypatch.setattr(  # [CHAT FIX 2]
        tenant_state.connection,  # [CHAT FIX 2]
        "fetchrow",  # [CHAT FIX 2]
        AsyncMock(side_effect=fetchrow),  # [CHAT FIX 2]
    )  # [CHAT FIX 2]
    monkeypatch.setattr(library, "get_single_document", detail)  # [CHAT FIX 2]
    response = TestClient(app).patch(  # [CHAT FIX 2]
        f"/api/v1/library/documents/{document_id}",  # [CHAT FIX 2]
        json={  # [CHAT FIX 2]
            "status": "active",  # [CHAT FIX 2]
            "reviewed_by": "018f3a10-0001-7000-8000-000000000009",  # [CHAT FIX 2]
            "reviewed_at": "caller-time",  # [CHAT FIX 2]
        },  # [CHAT FIX 2]
    )  # [CHAT FIX 2]
    assert response.status_code == expected  # [CHAT FIX 2]
    if expected == 200:  # [CHAT FIX 2]
        assert row["status"] == "active"  # [CHAT FIX 2]
        assert row["reviewed_by"] == tenant_state.user.id  # [CHAT FIX 2]
        assert row["reviewed_at"] == "database-now"  # [CHAT FIX 2]
        assert "reviewed_at = now()" in updates[0][0]  # [CHAT FIX 2]
    else:  # [CHAT FIX 2]
        assert row["status"] == "pending_review"  # [CHAT FIX 2]
        assert row["reviewed_by"] is None and row["reviewed_at"] is None  # [CHAT FIX 2]
