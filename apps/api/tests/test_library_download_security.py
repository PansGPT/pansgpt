@pytest.mark.asyncio  # [TENANT FIX 2]
@pytest.mark.parametrize("configured", [False, True])  # [TENANT FIX 2]
async def test_generated_artifact_links_use_artifact_route(  # [TENANT FIX 2]
    monkeypatch: pytest.MonkeyPatch,  # [TENANT FIX 2]
    configured: bool,  # [TENANT FIX 2]
) -> None:  # [TENANT FIX 2]
    upload = AsyncMock()  # [TENANT FIX 2]
    monkeypatch.setattr(  # [TENANT FIX 2]
        skills,  # [TENANT FIX 2]
        "r2_storage",  # [TENANT FIX 2]
        SimpleNamespace(is_configured=configured, upload_bytes=upload),  # [TENANT FIX 2]
    )  # [TENANT FIX 2]
    key = f"artifacts/{UNI_A}/018f3a10-0001-7000-8000-000000000001/pdf/output.pdf"
    if not configured:
        with pytest.raises(HTTPException) as error:
            await skills.skill_engine._safe_r2_upload(key, b"offline", "application/pdf")
        assert error.value.status_code == 503
        upload.assert_not_awaited()
        return
    result_key, url = await skills.skill_engine._safe_r2_upload(  # [TENANT FIX 2]
        key,  # [TENANT FIX 2]
        b"offline",  # [TENANT FIX 2]
        "application/pdf",  # [TENANT FIX 2]
        title="Study Notes",  # [TENANT FIX 2]
    )  # [TENANT FIX 2]
    assert result_key == key  # [TENANT FIX 2]
    assert url is not None  # [TENANT FIX 2]
    assert url.startswith("/api/v1/library/artifacts/download?")  # [TENANT FIX 2]
    assert "filename=Study%20Notes" in url  # [TENANT FIX 2]
    if configured:  # [TENANT FIX 2]
        upload.assert_awaited_once_with(key, b"offline", "application/pdf")  # [TENANT FIX 2]
    else:  # [TENANT FIX 2]
        upload.assert_not_awaited()  # [TENANT FIX 2]
