    download_state.user["roles"] = [role]  # [TENANT FIX 2]
    download_state.user["university_id"] = university  # [TENANT FIX 2]
    if download_state.document is not None:  # [TENANT FIX 2]
        download_state.document.update(  # [TENANT FIX 2]
            university_id=document_university,  # [TENANT FIX 2]
            status=document_status,  # [TENANT FIX 2]
            deleted_at="deleted" if deleted else None,  # [TENANT FIX 2]
        )  # [TENANT FIX 2]
    if not exists:  # [TENANT FIX 2]
        download_state.document = None  # [TENANT FIX 2]
    response = TestClient(app).get(  # [TENANT FIX 2]
        "/api/v1/library/documents/download",  # [TENANT FIX 2]
        params={"key": key},  # [TENANT FIX 2]
    )  # [TENANT FIX 2]
    assert response.status_code == expected  # [TENANT FIX 2]
    if expected == 200:  # [TENANT FIX 2]
        assert response.content == FILE_BYTES  # [TENANT FIX 2]
        assert response.headers["content-type"] == "application/pdf"  # [TENANT FIX 2]
        download_state.storage.assert_awaited_once_with(key)  # [TENANT FIX 2]
    else:  # [TENANT FIX 2]
        assert response.json() == {"detail": "File not found."}  # [TENANT FIX 2]
        download_state.storage.assert_not_awaited()  # [TENANT FIX 2]


