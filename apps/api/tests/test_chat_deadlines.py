@pytest.mark.parametrize("stage", ["creation", "lazy_first", "chunk_gap"])  # [CHAT FIX]
async def test_stalled_model_falls_back_without_partial_text(  # [CHAT FIX]
    bounded_engine: MultiTierLlmEngine,  # [CHAT FIX]
    monkeypatch: pytest.MonkeyPatch,  # [CHAT FIX]
    stage: str,  # [CHAT FIX]
) -> None:  # [CHAT FIX]
    closed = asyncio.Event()  # [CHAT FIX]

    async def stalled() -> AsyncIterator[str]:  # [CHAT FIX]
        try:  # [CHAT FIX]
            if stage == "chunk_gap":  # [CHAT FIX]
                yield "GARBLED PARTIAL"  # [CHAT FIX]
            await asyncio.Event().wait()  # [CHAT FIX]
            yield "unreachable"  # [CHAT FIX]
        finally:  # [CHAT FIX]
            closed.set()  # [CHAT FIX]

    async def turn(  # [CHAT FIX]
        model: str,  # [CHAT FIX]
        *args: object,  # [CHAT FIX]
    ) -> tuple[list[object], AsyncIterator[str]]:  # [CHAT FIX]
        if model == bounded_engine.primary_model:  # [CHAT FIX]
            if stage == "creation":  # [CHAT FIX]
                await asyncio.Event().wait()  # [CHAT FIX]
            return [], stalled()  # [CHAT FIX]
        return [], normal_stream()  # [CHAT FIX]

    call = AsyncMock(side_effect=turn)  # [CHAT FIX]
    monkeypatch.setattr(bounded_engine, "_call_gemma_turn", call)  # [CHAT FIX]
    events = await asyncio.wait_for(collect(bounded_engine), timeout=0.5)  # [CHAT FIX]
    text = "".join(  # [CHAT FIX]
        payload["token"]  # [CHAT FIX]
        for kind, payload, _ in events  # [CHAT FIX]
        if kind == "text_chunk"  # [CHAT FIX]
    )  # [CHAT FIX]
    if stage == "chunk_gap":  # [CHAT FIX 2]
        # Once streaming has started, the new contract requires an error, without fallback.  # [CHAT FIX 2]
        assert text == "GARBLED PARTIAL"  # [CHAT FIX 2]
        assert call.await_count == 1  # [CHAT FIX 2]
        errors = [payload for kind, payload, _ in events if kind == "error"]  # [CHAT FIX 2]
        assert len(errors) == 1  # [CHAT FIX 2]
        assert errors[0]["code"] == "TIMEOUT" and errors[0]["retryable"] is True  # [CHAT FIX 2]
        assert closed.is_set()  # [CHAT FIX 2]
        return  # [CHAT FIX 2]
    assert text == "Clean answer."  # [CHAT FIX]
    assert "GARBLED" not in text  # [CHAT FIX]
    assert call.await_count == 2  # [CHAT FIX]
    assert call.await_args_list[1].args[0] == bounded_engine.secondary_model  # [CHAT FIX]
    if stage != "creation":  # [CHAT FIX]
        assert closed.is_set()  # [CHAT FIX]


