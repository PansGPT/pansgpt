def test_prefix_verification_and_no_double_prefixing():  # [EMBED FIX]
    """Verify document and query text formatting, including title handling and idempotency."""  # [EMBED FIX]
    # Query prefixing  # [EMBED FIX]
    q1 = GeminiEmbeddingEngine.format_text("paracetamol mechanism", kind="query")  # [EMBED FIX]
    assert q1 == "task: search result | query: paracetamol mechanism"  # [EMBED FIX]
    # [EMBED FIX]
    q2 = GeminiEmbeddingEngine.format_text(q1, kind="query")  # [EMBED FIX]
    assert q2 == q1  # [EMBED FIX]
    # [EMBED FIX]
    # Document prefixing without title  # [EMBED FIX]
    d1 = GeminiEmbeddingEngine.format_text(
        "paracetamol dosage is 500mg", kind="document"
    )  # [EMBED FIX]
    assert d1 == "title: none | text: paracetamol dosage is 500mg"  # [EMBED FIX]
    # [EMBED FIX]
    # Document prefixing with title  # [EMBED FIX]
    d2 = GeminiEmbeddingEngine.format_text(  # [EMBED FIX]
        "paracetamol dosage is 500mg",
        kind="document",
        title="British National Formulary",  # [EMBED FIX]
    )  # [EMBED FIX]
    assert (
        d2 == "title: British National Formulary | text: paracetamol dosage is 500mg"
    )  # [EMBED FIX]
    # [EMBED FIX]
    # Idempotent document prefixing  # [EMBED FIX]
    d3 = GeminiEmbeddingEngine.format_text(d2, kind="document", title="Other Title")  # [EMBED FIX]
    assert d3 == d2  # [EMBED FIX]


