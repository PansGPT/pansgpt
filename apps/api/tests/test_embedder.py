@pytest.mark.asyncio  # [EMBED FIX]
async def test_embed_batch_calls_wrapped_content_objects(monkeypatch):  # [EMBED FIX]
    """Verify each batch makes one client call with types.Content objects."""  # [EMBED FIX]
    monkeypatch.setattr(settings, "EMBEDDER_FAKE_MODE", False)  # [EMBED FIX]
    monkeypatch.setattr(settings, "GEMINI_API_KEY", "test-key-mock")  # [EMBED FIX]
    # [EMBED FIX]
    mock_response = MagicMock()  # [EMBED FIX]
    mock_emb1 = MagicMock(values=[0.1] * settings.GEMINI_EMBEDDING_DIMENSIONS)  # [DIM 1536]
    mock_emb2 = MagicMock(values=[0.2] * settings.GEMINI_EMBEDDING_DIMENSIONS)  # [DIM 1536]
    mock_response.embeddings = [mock_emb1, mock_emb2]  # [EMBED FIX]
    # [EMBED FIX]
    mock_client = MagicMock()  # [EMBED FIX]
    mock_client.aio.models.embed_content = AsyncMock(return_value=mock_response)  # [EMBED FIX]
    # [EMBED FIX]
    with patch("google.genai.Client", return_value=mock_client):  # [EMBED FIX]
        engine = GeminiEmbeddingEngine()  # [EMBED FIX]
        texts = ["Text item 1", "Text item 2"]  # [EMBED FIX]
        vectors = await engine.embed_batch(texts, kind="document")  # [EMBED FIX]
        # [EMBED FIX]
        assert len(vectors) == 2  # [EMBED FIX]
        assert len(vectors[0]) == settings.GEMINI_EMBEDDING_DIMENSIONS  # [DIM 1536]
        assert mock_client.aio.models.embed_content.call_count == 1  # [EMBED FIX]
        # [EMBED FIX]
        _, kwargs = mock_client.aio.models.embed_content.call_args  # [EMBED FIX]
        contents = kwargs["contents"]  # [EMBED FIX]
        assert len(contents) == 2  # [EMBED FIX]
        assert isinstance(contents[0], types.Content)  # [EMBED FIX]
        assert contents[0].parts[0].text == "title: none | text: Text item 1"  # [EMBED FIX]
        assert contents[1].parts[0].text == "title: none | text: Text item 2"  # [EMBED FIX]
        assert (
            kwargs["config"].output_dimensionality == settings.GEMINI_EMBEDDING_DIMENSIONS
        )  # [DIM 1536]


