import uuid  # [TENANT FIX]

from fastapi import Depends, HTTPException  # [TENANT FIX]

from app.core.database import get_db_connection  # [TENANT FIX]
from app.core.dependencies import UserContext, get_current_user  # [TENANT FIX]


def require_university(user: UserContext) -> uuid.UUID:  # [TENANT FIX]
    if user.university_id is None:  # [TENANT FIX]
        raise HTTPException(  # [TENANT FIX]
            status_code=403,  # [TENANT FIX]
            detail="A university is required to access this resource.",  # [TENANT FIX]
        )  # [TENANT FIX]
    return user.university_id  # [TENANT FIX]


async def check_document_scope(  # [TENANT FIX]
    document_id: str,  # [TENANT FIX]
    user: UserContext,  # [TENANT FIX]
    active_only: bool = False,  # [TENANT FIX]
) -> None:  # [TENANT FIX]
    university_id = require_university(user)  # [TENANT FIX]
    try:  # [TENANT FIX]
        doc_id = uuid.UUID(document_id)  # [TENANT FIX]
    except ValueError as exc:  # [TENANT FIX]
        raise HTTPException(status_code=404, detail="Document not found.") from exc  # [TENANT FIX]
    can_review = not active_only and bool(  # [TENANT FIX]
        set(user.roles) & {"university_admin", "super_admin", "lecturer"}  # [TENANT FIX]
    )  # [TENANT FIX]
    async with get_db_connection() as conn:  # [TENANT FIX]
        if conn is None:  # [TENANT FIX]
            raise HTTPException(  # [TENANT FIX]
                status_code=503,  # [TENANT FIX]
                detail="Unable to verify document access.",  # [TENANT FIX]
            )  # [TENANT FIX]
        row = await conn.fetchrow(  # [TENANT FIX]
            "SELECT id FROM public.documents WHERE id = $1 AND university_id = $2 "  # [TENANT FIX]
            "AND deleted_at IS NULL AND (status = 'active' OR $3);",  # [TENANT FIX]
            doc_id,  # [TENANT FIX]
            university_id,  # [TENANT FIX]
            can_review,  # [TENANT FIX]
        )  # [TENANT FIX]
    if row is None:  # [TENANT FIX]
        raise HTTPException(status_code=404, detail="Document not found.")  # [TENANT FIX]


async def require_scoped_document(  # [TENANT FIX]
    document_id: str,  # [TENANT FIX]
    current_user: UserContext = Depends(get_current_user),  # [TENANT FIX]
) -> str:  # [TENANT FIX]
    await check_document_scope(document_id, current_user)  # [TENANT FIX]
    return document_id  # [TENANT FIX]


async def require_owned_session(  # [TENANT FIX]
    session_id: str,  # [TENANT FIX]
    user: UserContext,  # [TENANT FIX]
    parent_message_id: str | None = None,  # [TENANT FIX]
) -> None:  # [TENANT FIX]
    require_university(user)  # [TENANT FIX]
    try:  # [TENANT FIX]
        session_uuid = uuid.UUID(session_id)  # [TENANT FIX]
        parent_uuid = uuid.UUID(parent_message_id) if parent_message_id else None  # [TENANT FIX]
    except ValueError as exc:  # [TENANT FIX]
        raise HTTPException(  # [TENANT FIX]
            status_code=404,  # [TENANT FIX]
            detail="Conversation not found.",  # [TENANT FIX]
        ) from exc  # [TENANT FIX]
    parent = None  # [TENANT FIX]
    async with get_db_connection() as conn:  # [TENANT FIX]
        if conn is None:  # [TENANT FIX]
            raise HTTPException(  # [TENANT FIX]
                status_code=503,  # [TENANT FIX]
                detail="Unable to verify conversation access.",  # [TENANT FIX]
            )  # [TENANT FIX]
        session = await conn.fetchrow(  # [TENANT FIX]
            "SELECT id, document_id FROM public.chat_sessions "  # [TENANT FIX]
            "WHERE id = $1 AND user_id = $2 AND deleted_at IS NULL;",  # [TENANT FIX]
            session_uuid,  # [TENANT FIX]
            user.id,  # [TENANT FIX]
        )  # [TENANT FIX]
        if session is not None and parent_uuid is not None:  # [TENANT FIX]
            parent = await conn.fetchrow(  # [TENANT FIX]
                "SELECT id FROM public.chat_messages WHERE id = $1 AND session_id = $2;",  # [TENANT FIX]
                parent_uuid,  # [TENANT FIX]
                session_uuid,  # [TENANT FIX]
            )  # [TENANT FIX]
    if session is None:  # [TENANT FIX]
        raise HTTPException(status_code=404, detail="Conversation not found.")  # [TENANT FIX]
    if parent_uuid is not None and parent is None:  # [TENANT FIX]
        raise HTTPException(status_code=404, detail="Parent message not found.")  # [TENANT FIX]
    if session["document_id"] is not None:  # [TENANT FIX]
        await check_document_scope(  # [TENANT FIX]
            str(session["document_id"]),  # [TENANT FIX]
            user,  # [TENANT FIX]
            active_only=True,  # [TENANT FIX]
        )  # [TENANT FIX]
